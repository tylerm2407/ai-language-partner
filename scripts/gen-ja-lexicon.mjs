/**
 * Generates lib/script-input/ja-lexicon.ts — the kana -> kanji conversions the
 * in-app Japanese input method offers.
 *
 * Source is migration 138, which holds one script_choice row per kanji-bearing
 * Japanese card, each carrying the kanji in `correct_answer` and its reading in
 * `metadata.reading`. That is the same pairing a learner needs to convert, and
 * it is already the curriculum's own, so the candidate list can never offer a
 * spelling the course does not teach.
 *
 * Run: node scripts/gen-ja-lexicon.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sql = readFileSync(join(root, 'supabase', 'migrations', '138_script_choice_kanji.sql'), 'utf8');

/** reading -> kanji spellings, in the order the migration lists them. */
const byReading = new Map();
const ROW = /'Which is the kanji for ([^ ]+) \([^)]*\)\?',\s*'([^']+)'/g;
for (const [, reading, kanji] of sql.matchAll(ROW)) {
  const list = byReading.get(reading) ?? [];
  if (!list.includes(kanji)) list.push(kanji);
  byReading.set(reading, list);
}

const lines = [...byReading]
  .sort((a, b) => a[0].localeCompare(b[0]))
  .map(([reading, kanji]) => `${reading}\t${kanji.join('|')}`);

const out = `/**
 * Kana -> kanji candidates for the in-app Japanese input method.
 *
 * GENERATED by scripts/gen-ja-lexicon.mjs — do not edit by hand. Every pair is
 * a word the Japanese course teaches, taken from migration 138's script_choice
 * rows (kanji in the answer, reading in the metadata).
 *
 * Curriculum-scoped on purpose, for the reason lib/script-input/zh-lexicon.ts
 * gives: a general Japanese IME needs a dictionary and a morphological analyser
 * we do not ship. Kana is always produced directly from romaji and, under the
 * orthography ruling of 2026-09-16, kana is itself a correct answer — so a
 * learner is never blocked by a missing conversion, only offered fewer.
 *
 * ${lines.length} readings.
 */

/** \`reading\\tkanji|kanji\`, one per line. */
export const JA_LEXICON = \`${lines.join('\n')}\`;
`;

writeFileSync(join(root, 'lib', 'script-input', 'ja-lexicon.ts'), out);
console.log(`readings: ${lines.length}  bytes: ${out.length}`);
