export function chineseAcceptedAlternatives(set) {
  const get = lessonRefs(set.snapshot, 'zh');
  const alreadyPatched = new Map();
  for (const patch of set.patches()) {
    if (patch.table === 'exercises' && Object.hasOwn(patch.after, 'accepted_answers')) alreadyPatched.set(patch.id, patch);
  }
  const skipped = [];
  for (const [number, key, type, lessonTitle, current, additions] of chineseAlternativeRows) {
    const { ref, exercise, lesson } = get(number);
    if (exercise.correct_answer !== key || exercise.type !== type || lesson.title !== lessonTitle) {
      throw new Error(`Unexpected frozen context: ${ref}`);
    }
    const frozen = exercise.accepted_answers ?? [];
    if (frozen.length !== current.length || frozen.some((value, index) => value !== current[index])) {
      throw new Error(`Frozen accepted_answers changed since review: ${ref}`);
    }
    // Existing-plus-additions. Nothing is ever dropped, and an addition that
    // duplicates the key or an existing alternative is an authoring error, not
    // something to silently de-duplicate.
    for (const addition of additions) {
      if (addition === key || frozen.includes(addition)) throw new Error(`Addition already accepted: ${ref}: ${addition}`);
      if (additions.indexOf(addition) !== additions.lastIndexOf(addition)) throw new Error(`Duplicate addition: ${ref}: ${addition}`);
      if ((exercise.options ?? []).includes(addition)) throw new Error(`Addition is an authored option: ${ref}: ${addition}`);
    }
    // Another producer owning this field is a reconciliation question for the
    // integration owner, not something to overwrite or quietly drop.
    if (alreadyPatched.has(exercise.id)) { skipped.push(ref); continue; }
    set.update('exercises', exercise.id, { accepted_answers: [...frozen, ...additions] }, `${ref}: The full exact lesson was reread. Each alternative was judged against this prompt's own wording and against every sibling item in the same unit, then added to accepted_answers only where it is standard mainland Mandarin (or, for translate_to_native, standard English), is covered by the gloss the prompt actually gives, fits the prompt's fragment, and is not the key or a distractor of another item in the unit. Existing entries are preserved unchanged; no key, prompt or option is touched. Traditional-script and punctuation-only variants are deliberately excluded. This text review does not certify generated pronunciation or open production.`, ['MDBG Chinese-English dictionary (CC-CEDICT)', '现代汉语词典 (Xiandai Hanyu Cidian), 7th edition']);
  }
  if (skipped.length) throw new Error(`accepted_answers already patched by another producer; reconcile before building: ${skipped.join(', ')}`);
}
